/* Generate the browser fallback and dated HTML labels from the canonical snapshot. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
function build(){
 const data=JSON.parse(fs.readFileSync(path.join(root,'data/rates.json'),'utf8'));
 const snapshot='/* Generated by scripts/build_rate_assets.cjs. */\nwindow.MPG_RATE_SNAPSHOT = '+JSON.stringify(data,null,2)+';\n';
 fs.writeFileSync(path.join(root,'js/rate-snapshot.js'),snapshot);
 const hash=s=>crypto.createHash('sha256').update(s).digest('hex').slice(0,12);
 const snapshotUrl='/js/rate-snapshot.js?v='+hash(snapshot),ratesUrl='/js/rates.js?v='+hash(fs.readFileSync(path.join(root,'js/rates.js')));
 for(const dir of ['', 'blog','authors'])for(const name of fs.readdirSync(path.join(root,dir)).filter(x=>x.endsWith('.html'))){
  const file=path.join(root,dir,name);let s=fs.readFileSync(file,'utf8');
  if(!/src="\/js\/rates\.js/.test(s))continue;
  s=s.replace(/<script[^>]+src="\/js\/rate-snapshot\.js[^\"]*"[^>]*><\/script>\s*/g,'');
  s=s.replace(/<script[^>]+src="\/js\/rates\.js[^\"]*"[^>]*><\/script>/g,`<script src="${snapshotUrl}" defer></script>\n<script src="${ratesUrl}" defer></script>`);
  s=s.replace(/(<([a-z][\w-]*)\b[^>]*\bdata-rate(?:-unavailable)?="([\w]+)\.([\w]+)"[^>]*>)[^<]*(<\/\2>)/gi,(all,start,tag,country,key,end)=>data.rates[country]?.[key]?start.replace('data-rate-unavailable=', 'data-rate=')+esc(data.rates[country][key].formatted)+end:start.replace(/data-rate(?:-unavailable)?=/, 'data-rate-unavailable=')+'Lender quote'+end);
  fs.writeFileSync(file,s);
 }
 console.log('Built browser rate snapshot and synchronized labeled HTML rates.');
}
if(require.main===module)build();module.exports={build};
